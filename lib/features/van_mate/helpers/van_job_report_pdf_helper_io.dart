Future<String> buildVanJobReportPdfPath(VanJobReportData report) async {
  final document = pw.Document();
  final logo = await _loadLogo(report.businessProfile.logoPath);

  document.addPage(
    pw.MultiPage(
      pageFormat: PdfPageFormat.a4,
      margin: const pw.EdgeInsets.all(32),
      theme: pw.ThemeData.withFont(),
      build: (context) => [
        _header(report, logo),
        pw.SizedBox(height: 18),
        _summaryCard(report),
        pw.SizedBox(height: 18),
        _sectionTitle('Jobs'),
        pw.SizedBox(height: 8),
        _jobsTable(report),
        if (report.entries.any(
          (entry) => (entry.notes ?? '').trim().isNotEmpty,
        )) ...[
          pw.SizedBox(height: 18),
          _sectionTitle('Notes'),
          pw.SizedBox(height: 8),
          _notesList(report),
        ],
        pw.SizedBox(height: 24),
        pw.Center(
          child: pw.Text(
            'Generated by Van Mate',
            style: pw.TextStyle(
              fontSize: 9,
              color: PdfColors.grey600,
              fontWeight: pw.FontWeight.bold,
            ),
          ),
        ),
      ],
    ),
  );

  final directory = await getTemporaryDirectory();
  final fileName = _safeFileName(report);
  final file = File('${directory.path}${Platform.pathSeparator}$fileName');
  await file.writeAsBytes(await document.save(), flush: true);
  return file.path;
}

Future<pw.MemoryImage?> _loadLogo(String? logoPath) async {
  final resolvedPath = resolveSavedVanBusinessLogoPath(logoPath);
  if (resolvedPath == null) {
    return null;
  }

  try {
    final bytes = await File(resolvedPath).readAsBytes();
    return pw.MemoryImage(bytes);
  } catch (error) {
    if (kDebugMode) {
      debugPrint('Van Mate job report logo load failed: $error');
    }
    return null;
  }
}

