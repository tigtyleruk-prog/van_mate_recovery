pw.Widget _sectionTitle(String title) {
  return pw.Text(
    title,
    style: pw.TextStyle(fontSize: 13, fontWeight: pw.FontWeight.bold),
  );
}

pw.Widget _jobsTable(VanJobReportData report) {
  final rows = report.entries.isEmpty
      ? [
          ['No completed jobs', '', '', '', '', '', '', ''],
        ]
      : report.entries
            .map(
              (entry) => [
                entry.customerName,
                entry.jobTitle,
                entry.reportDateSummary,
                entry.quoteLabel.replaceFirst('Quote: ', ''),
                entry.invoiceLabel.replaceFirst('Invoice: ', ''),
                entry.hasInvoice
                    ? formatCurrency(entry.invoiceTotal ?? 0)
                    : '-',
                entry.estimatedMiles == null
                    ? '-'
                    : formatVanMileage(entry.estimatedMiles ?? 0),
                entry.exactPinSaved ? 'Saved' : 'Not saved',
              ],
            )
            .toList();

  return pw.Table(
    border: pw.TableBorder.all(color: PdfColors.grey300),
    columnWidths: const {
      0: pw.FlexColumnWidth(1.6),
      1: pw.FlexColumnWidth(1.4),
      2: pw.FlexColumnWidth(1.0),
      3: pw.FlexColumnWidth(0.9),
      4: pw.FlexColumnWidth(1.0),
      5: pw.FlexColumnWidth(0.9),
      6: pw.FlexColumnWidth(0.8),
      7: pw.FlexColumnWidth(0.8),
    },
    children: [
      pw.TableRow(
        decoration: const pw.BoxDecoration(color: PdfColors.grey200),
        children: [
          _tableCell('Customer', bold: true),
          _tableCell('Job', bold: true),
          _tableCell('Completed', bold: true),
          _tableCell('Quote', bold: true),
          _tableCell('Invoice', bold: true),
          _tableCell('Total', bold: true),
          _tableCell('Miles', bold: true),
          _tableCell('Pin', bold: true),
        ],
      ),
      for (final row in rows)
        pw.TableRow(
          children: [
            _tableCell(row[0]),
            _tableCell(row[1]),
            _tableCell(row[2]),
            _tableCell(row[3], alignRight: true),
            _tableCell(row[4], alignRight: true),
            _tableCell(row[5], alignRight: true),
            _tableCell(row[6], alignRight: true),
            _tableCell(row[7]),
          ],
        ),
    ],
  );
}

pw.Widget _notesList(VanJobReportData report) {
  final notes = report.entries
      .where((entry) => (entry.notes ?? '').trim().isNotEmpty)
      .map(
        (entry) =>
            '${sanitizeVanText(entry.customerName).trim()} - ${sanitizeVanText(entry.jobTitle).trim()}: ${sanitizeVanText(entry.notes).trim()}',
      )
      .toList();

  return pw.Container(
    width: double.infinity,
    padding: const pw.EdgeInsets.all(12),
    decoration: pw.BoxDecoration(
      color: PdfColors.grey100,
      borderRadius: pw.BorderRadius.circular(12),
      border: pw.Border.all(color: PdfColors.grey300),
    ),
    child: pw.Column(
      crossAxisAlignment: pw.CrossAxisAlignment.start,
      children: [
        for (var i = 0; i < notes.length; i++) ...[
          pw.Text(notes[i]),
          if (i < notes.length - 1) pw.SizedBox(height: 6),
        ],
      ],
    ),
  );
}

pw.Widget _tableCell(
  String value, {
  bool bold = false,
  bool alignRight = false,
}) {
  return pw.Padding(
    padding: const pw.EdgeInsets.all(8),
    child: pw.Align(
      alignment: alignRight
          ? pw.Alignment.centerRight
          : pw.Alignment.centerLeft,
      child: pw.Text(
        value,
        style: pw.TextStyle(
          fontWeight: bold ? pw.FontWeight.bold : pw.FontWeight.normal,
          fontSize: 9.5,
        ),
      ),
    ),
  );
}

String _safeFileName(VanJobReportData report) {
  final suffix = report.range == VanJobReportRange.today
      ? formatVanDateForFile(report.rangeStart)
      : 'Week-${formatVanDateForFile(report.rangeStart)}';
  return 'VanMate-Job-Report-$suffix.pdf';
}
